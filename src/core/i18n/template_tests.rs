#[test]
fn singular_counts_keep_the_english_wording_and_zero_and_many_stay_plural() {
  for (count, play, track, hit) in [
    (0, "plays", "tracks", "track hits"),
    (1, "play", "track", "track hit"),
    (2, "plays", "tracks", "track hits"),
  ] {
    assert_eq!(
      EN.screens.folder_tracks("Folder", count),
      format!("Folder ({count} {track})")
    );
    assert_eq!(
      EN.screens.stats_totals(count as u64, "2m"),
      format!("  {count} {play} · 2m listened")
    );
    assert_eq!(
      EN.status.infra.history_plays(count as u64, "2m"),
      format!("{count} {play} · 2m")
    );
    assert_eq!(
      EN.status.infra.history_track_hits(count as u64, "2m"),
      format!("{count} {hit} · 2m")
    );
  }
}
