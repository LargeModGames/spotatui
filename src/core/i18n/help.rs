impl HelpStrings {
  pub fn arrow_key(&self, key: &str) -> String {
    format_template(self.arrow_key_template, &[("key", key)])
  }
  pub fn key_alternative(&self, first: &str, second: &str) -> String {
    format_template(
      self.key_alternative_template,
      &[("first", first), ("second", second)],
    )
  }

  pub fn no_matches(&self, filter: &str) -> String {
    format_template(self.no_matches_template, &[("filter", filter)])
  }

  pub fn matches(&self, filter: &str) -> String {
    format_template(self.matches_template, &[("filter", filter)])
  }

  pub fn filter_count_hint(&self, count: usize) -> String {
    format_template(
      self.filter_count_hint_template,
      &[("count", &count.to_string())],
    )
  }

  pub fn not_for_source(&self, source: &str) -> String {
    format_template(self.not_for_source_template, &[("source", source)])
  }

  pub fn only_for_source(&self, source: &str) -> String {
    format_template(self.only_for_source_template, &[("source", source)])
  }

  pub fn unavailable_description(&self, description: &str, hint: &str) -> String {
    format_template(
      self.unavailable_description_template,
      &[("description", description), ("hint", hint)],
    )
  }
}
